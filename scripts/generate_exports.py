"""Regenerate `src/shoal/payloads/__init__.py` from the payload modules.

Every public class and every public `Final` constant defined in a payload module is re-exported, so
`from shoal.payloads import User` always works and the export list can never drift from the modules.
Run it after adding or renaming a payload; `tests/test_conventions.py` fails if it is stale.

    uv run python scripts/generate_exports.py
"""

import ast
import sys
from pathlib import Path

PAYLOADS = Path(__file__).resolve().parent.parent / "src" / "shoal" / "payloads"
TARGET = PAYLOADS / "__init__.py"
HEADER = '''"""Typed mirrors of Discord's JSON objects, one module per domain.

Every type links to the Discord docs section it mirrors. Everything is re-exported here, so
`from shoal.payloads import User, Guild` works. This file is generated by
`scripts/generate_exports.py`; do not edit it by hand.
"""
'''


def public_names(path: Path) -> list[str]:
    """Public classes, functions and `Final` constants defined at the top level of a module."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef | ast.FunctionDef) and not node.name.startswith("_"):
            names.append(node.name)
        elif (
            isinstance(node, ast.AnnAssign)
            and isinstance(node.target, ast.Name)
            and not node.target.id.startswith("_")
            and "Final" in ast.unparse(node.annotation)
        ):
            names.append(node.target.id)
    return names


def _group(name: str) -> int:
    """Ruff's order: CONSTANTS, then Classes, then functions."""
    if name.isupper():
        return 0
    return 1 if name[0].isupper() else 2


def render() -> str:
    """The full text of the generated `__init__.py`."""
    imports: list[str] = []
    exported: list[str] = []
    for path in sorted(PAYLOADS.glob("*.py")):
        if path.name == "__init__.py":
            continue
        names = sorted(public_names(path), key=lambda name: (_group(name), name.casefold()))
        if not names:
            continue
        exported.extend(names)
        body = "".join(f"    {name},\n" for name in names)
        imports.append(f"from shoal.payloads.{path.stem} import (\n{body})\n")
    ordered = sorted(exported, key=lambda name: (_group(name), name))
    listing = "".join(f'    "{name}",\n' for name in ordered)
    return f"{HEADER}\n{''.join(imports)}\n__all__ = [\n{listing}]\n"


def main() -> int:
    """Write the file, or with `--check` report whether it is up to date."""
    expected = render()
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != expected:
            print("src/shoal/payloads/__init__.py is stale; run scripts/generate_exports.py")
            return 1
        return 0
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
